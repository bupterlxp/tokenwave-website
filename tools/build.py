#!/usr/bin/env python3
"""Build every generated page of tokenwave.ai from data/.

Single sources of truth:
    data/benchmarks/<slug>.json   scraped benchmark records (tools/scrape.py)
    data/models.json              model id -> {name, org, color}
    data/focus_en.json            English overrides for Chinese source fields
    data/featured.json            curated cards for the benchmarks list page
    data/blog/<slug>.json         hand-polished article copy

Outputs:
    benchmarks/<slug>.html  x48       blog/<slug>.html  x8
    benchmarks.html                   blog.html
    compare.html                      static/js/compare-app.js
    data/compare.json                 sitemap.xml, robots.txt

Deterministic and idempotent: re-running with unchanged data produces
byte-identical output (verify with `git diff` / checksums).

Run:  python3 tools/build.py
"""

import html as htmlmod
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
TPL = Path(__file__).resolve().parent / "templates"

SITE = "https://tokenwave.ai"
DOMAIN_ORDER = ["agent", "multimodal", "aigc", "llm"]
DOMAIN_SHORT = {"agent": "Agent", "multimodal": "MLLM", "aigc": "AIGC", "llm": "LLM"}

GEN_NOTE = "<!-- Generated by tools/build.py — edit data/ or tools/, not this file. -->"


def esc(s):
    return htmlmod.escape(str(s), quote=True)


def fmt_score(v):
    return f"{v:g}" if isinstance(v, (int, float)) else "–"


# ── data loading ─────────────────────────────────────────────────────────────

def load():
    benches = {}
    for f in sorted((DATA / "benchmarks").glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        benches[d["slug"]] = d

    focus_en = json.loads((DATA / "focus_en.json").read_text(encoding="utf-8"))
    for slug, over in focus_en.items():
        if slug.startswith("_") or slug not in benches:
            continue
        g = benches[slug]["at_a_glance"]
        if over.get("focus"):
            g["focus"] = over["focus"]
        if over.get("setting"):
            g["setting"] = over["setting"]

    models = json.loads((DATA / "models.json").read_text(encoding="utf-8"))
    featured = json.loads((DATA / "featured.json").read_text(encoding="utf-8"))["featured"]

    posts = []
    for f in sorted((DATA / "blog").glob("*.json")):
        posts.append(json.loads(f.read_text(encoding="utf-8")))
    posts.sort(key=lambda p: p["date"], reverse=True)

    editorial = {}
    ed_dir = DATA / "editorial"
    if ed_dir.exists():
        for f in sorted(ed_dir.glob("*.json")):
            e = json.loads(f.read_text(encoding="utf-8"))
            editorial[e["slug"]] = e

    return benches, models, featured, posts, editorial



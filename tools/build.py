def metric_rmax(b):
    """Upper bound of the primary metric's range, e.g. "[0, 100]" -> 100."""
    direction, rng = "higher", None
    for m in b["metrics"]:
        if m["name"] == b.get("leaderboard_metric"):
            direction, rng = m["direction"], m.get("range")
            break
    else:
        if b["metrics"]:
            direction, rng = b["metrics"][0]["direction"], b["metrics"][0].get("range")
    rmax = 100.0
    if rng:
        m2 = re.search(r",\s*([0-9.]+)\s*\]", rng)
        if m2:
            rmax = float(m2.group(1))
    return rmax, direction


def build_home_data(benches, careers):
    """Real data for the home page: board marquee and frontier chart."""
    rows = []
    for b in benches.values():
        lead = leader_of(b)
        if not lead:
            continue
        rows.append({
            "u": b["at_a_glance"].get("data_updated") or "",
            "n": b["name"],
            "m": lead["model"],
            "s": f'{fmt_score(lead["score"])} {b.get("leaderboard_metric") or "score"}',
            "h": f"benchmarks/{file_slug(b['slug'])}.html",
        })
    rows.sort(key=lambda r: (r["u"], r["n"]), reverse=True)
    rows = [{k: r[k] for k in ("n", "m", "s", "h")} for r in rows[:16]]

    # Flagship board for the frontier chart: the FDE anchor benchmark.
    fb = benches["workflow_gym"]
    frontier = {
        "name": fb["name"],
        "metric": fb.get("leaderboard_metric") or "Score",
        "href": f"benchmarks/{file_slug(fb['slug'])}.html",
        "rows": [{"m": r["model"], "s": r["score"]}
                 for r in fb["leaderboard"][:5] if isinstance(r["score"], (int, float))],
    }

    js = ("/* Generated by tools/build.py — real leaderboard data. */\n"
          f"window.TW_BOARD = {json.dumps(rows, ensure_ascii=False)};\n"
          f"window.TW_FRONTIER = {json.dumps(frontier, ensure_ascii=False)};\n")
    write("static/js/home-data.js", js)
    return len(rows)


def count_models_tracked(benches):
    ids = set()
    for b in benches.values():
        if not is_benchmark_paper(b):
            continue
        for r in b["leaderboard"]:
            if r.get("model_id"):
                ids.add(r["model_id"])
    return len(ids)



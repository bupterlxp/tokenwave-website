def stamp_static_assets():
    versions = {
        "static/css/style.css": V_CSS,
        "static/js/particles.js": V_PARTICLES,
        "static/js/transition.js": V_TRANSITION,
        "static/js/site.js": V_SITE,
        # generated during this build, so hash at call time
        "static/js/home-data.js": asset_v("static/js/home-data.js"),
    }
    pat = re.compile(r'(static/(?:css|js)/[A-Za-z0-9_.-]+)(\?v=[0-9a-f]+)?')

    def sub(m):
        v = versions.get(m.group(1))
        return f"{m.group(1)}?v={v}" if v else m.group(1)

    for rel in ["index.html", "joinus.html"]:
        f = ROOT / rel
        f.write_text(pat.sub(sub, f.read_text(encoding="utf-8")), encoding="utf-8")


# ── seo files ────────────────────────────────────────────────────────────────

def build_seo(benches, posts):
    latest_bench = max(b["at_a_glance"].get("data_updated") or "2026-01-01" for b in benches.values())
    latest_post = max(p["date"] for p in posts)
    latest = max(latest_bench, latest_post)

    urls = [
        ("", latest, "weekly", "1.0"),
        ("careers.html", latest_bench, "weekly", "0.9"),
        ("research.html", latest_post, "weekly", "0.8"),
        ("joinus.html", latest, "monthly", "0.5"),
    ]
    for b in sorted(benches.values(), key=lambda x: file_slug(x["slug"])):
        urls.append((f"benchmarks/{file_slug(b['slug'])}.html",
                     b["at_a_glance"].get("data_updated") or latest_bench, "monthly", "0.7"))
    for p in posts:
        urls.append((f"research/{p['slug']}.html", p["date"], "monthly", "0.6"))

    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for path, mod, freq, pri in urls:
        lines.append(f"  <url><loc>{SITE}/{path}</loc><lastmod>{mod}</lastmod>"
                     f"<changefreq>{freq}</changefreq><priority>{pri}</priority></url>")
    lines.append("</urlset>")
    write("sitemap.xml", "\n".join(lines) + "\n")

    write("robots.txt", f"User-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n")



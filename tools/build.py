#!/usr/bin/env python3
"""Build every generated page of tokenwave.ai from data/.

Single sources of truth:
    data/benchmarks/<slug>.json   scraped benchmark records (tools/scrape.py)
    data/models.json              model id -> {name, org, color}
    data/focus_en.json            English overrides for Chinese source fields
    data/careers.json             career tracks -> benchmark slugs + copy
    data/blog/<slug>.json         hand-polished article copy

Outputs:
    benchmarks/<slug>.html  x50       research/<slug>.html
    careers.html                      research.html
    benchmarks.html (redirect)        blog.html (redirect)
    sitemap.xml, robots.txt

data/blog/archive/ holds written-but-unpublished notes; only top-level
data/blog/*.json is published.

Deterministic and idempotent: re-running with unchanged data produces
byte-identical output (verify with `git diff` / checksums).

Run:  python3 tools/build.py
"""

import hashlib
import html as htmlmod
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
TPL = Path(__file__).resolve().parent / "templates"


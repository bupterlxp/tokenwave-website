def write(rel, content):
    out = ROOT / rel
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")


# ── shared fragments ─────────────────────────────────────────────────────────

def file_slug(slug):
    return slug.replace("_", "-")


def leader_of(b):
    lb = b["leaderboard"]
    return lb[0] if lb else None


def bench_meta_line(b):
    lead = leader_of(b)
    bits = []
    if lead:
        bits.append(f'<span class="lead">🏆 {esc(lead["model"])}: {fmt_score(lead["score"])}</span>')
    bits.append(esc(b["subcategory"]))
    updated = b["at_a_glance"].get("data_updated")
    if updated:
        bits.append(f"updated {esc(updated)}")
    return '\n                <span class="sep">·</span>\n                '.join(bits)


def card(depth, href, image, meta_html, title, blurb_html):
    return f"""
    <article class="card card-row">
        <div class="card-image" style="background-image: url('{depth}{image}');"></div>
        <div class="card-body">
            <div class="card-meta">
                {meta_html}
            </div>
            <h3><a href="{href}">{esc(title)}</a></h3>
            <p>{blurb_html}</p>
        </div>
    </article>
"""


def leaderboard_table(b, top=None, depth=""):
    metric = b.get("leaderboard_metric") or "Score"
    rows = b["leaderboard"][:top] if top else b["leaderboard"]
    has_date = any(r.get("date") for r in rows)
    head_cells = f"<th>#</th><th>Model</th><th>{esc(metric)}</th><th>Source</th>"
    if has_date:
        head_cells += "<th>Date</th>"
    out = [f"<table class=\"data-table\">\n            <thead>\n                <tr>{head_cells}</tr>\n            </thead>\n            <tbody>"]
    src_label = {"official": "Official", "community": "Community", "self_reported": "Self-reported"}
    for r in rows:
        cls = ' class="lead-row"' if r["rank"] == 1 else ""
        cells = [
            f'<td><span class="rank">{r["rank"]}</span></td>',
            f'<td>{esc(r["model"])}</td>',
            f'<td class="num">{fmt_score(r["score"])}</td>',
            f'<td>{esc(src_label.get(r.get("source"), r.get("source") or "–"))}</td>',
        ]
        if has_date:
            cells.append(f'<td class="num">{esc(r.get("date") or "–")}</td>')
        out.append(f"                <tr{cls}>{''.join(cells)}</tr>")
    out.append("            </tbody>\n        </table>")
    return "\n".join(out)



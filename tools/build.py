GEN_NOTE = "<!-- Generated by tools/build.py — edit data/ or tools/, not this file. -->"


def asset_v(rel):
    """Short content hash for cache-busting ?v= query strings."""
    return hashlib.md5((ROOT / rel).read_bytes()).hexdigest()[:8]


def asset_url(rel):
    """Return a local asset URL whose query changes when the file changes."""
    return f"{rel}?v={asset_v(rel)}"


V_CSS = asset_v("static/css/style.css")
V_PARTICLES = asset_v("static/js/particles.js")
V_TRANSITION = asset_v("static/js/transition.js")
V_SITE = asset_v("static/js/site.js")
V_HOME = ""  # set in main() after home-data.js is generated


def esc(s):
    return htmlmod.escape(str(s), quote=True)


def fmt_score(v):
    return f"{v:g}" if isinstance(v, (int, float)) else "–"


# ── data loading ─────────────────────────────────────────────────────────────

def load():
    benches = {}
    for f in sorted((DATA / "benchmarks").glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        benches[d["slug"]] = d

    focus_en = json.loads((DATA / "focus_en.json").read_text(encoding="utf-8"))
    for slug, over in focus_en.items():
        if slug.startswith("_") or slug not in benches:
            continue
        g = benches[slug]["at_a_glance"]
        if over.get("focus"):
            g["focus"] = over["focus"]
        if over.get("setting"):
            g["setting"] = over["setting"]

    models = json.loads((DATA / "models.json").read_text(encoding="utf-8"))

    careers = json.loads((DATA / "careers.json").read_text(encoding="utf-8"))["careers"]
    assigned = [s for c in careers for s in c["benchmarks"]]
    unknown = set(assigned) - set(benches)
    dupes = {s for s in assigned if assigned.count(s) > 1}
    if unknown or dupes:
        raise SystemExit(f"careers.json error — unknown: {unknown or '{}'}, "
                         f"duplicated: {dupes or '{}'}")

    posts = []
    for f in sorted((DATA / "blog").glob("*.json")):
        posts.append(json.loads(f.read_text(encoding="utf-8")))
    posts.sort(key=lambda p: p["date"], reverse=True)

    research = json.loads((DATA / "research.json").read_text(encoding="utf-8"))
    for f in research["featured"]:
        if f["slug"] not in benches:
            raise SystemExit(f"research.json: unknown featured slug {f['slug']!r}")

    editorial = {}
    ed_dir = DATA / "editorial"
    if ed_dir.exists():
        for f in sorted(ed_dir.glob("*.json")):
            e = json.loads(f.read_text(encoding="utf-8"))
            editorial[e["slug"]] = e

    return benches, models, careers, posts, editorial, research



def read_minutes(post):
    words = 0
    for blk in post["body"]:
        for key in ("text",):
            if blk.get(key):
                words += len(blk[key].split())
        for item in blk.get("items", []):
            words += len(item.split())
    words += len(post["summary"].split())
    return max(1, round(words / 200))


